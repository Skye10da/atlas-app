/// Represents an edge in the entity co-occurrence graph within a novel.
class StoryCooccurrence {
  const StoryCooccurrence({
    required this.id,
    required this.bookId,
    this.readThroughId = 'default',
    required this.entityAId,
    required this.entityBId,
    required this.weight,
    required this.lastSeenChapter,
  });

  factory StoryCooccurrence.fromJson(Map<String, dynamic> json) {
    return StoryCooccurrence(
      id: json['id'] as String,
      bookId: json['bookId'] as String,
      readThroughId: json['readThroughId'] as String? ?? 'default',
      entityAId: json['entityAId'] as String,
      entityBId: json['entityBId'] as String,
      weight: (json['weight'] as num?)?.toInt() ?? 1,
      lastSeenChapter: (json['lastSeenChapter'] as num?)?.toInt() ?? 1,
    );
  }

  final String id;
  final String bookId;
  final String readThroughId;
  final String entityAId;
  final String entityBId;

  /// Frequency count of how many chapters/scenes both entities appeared together.
  final int weight;

  /// Most recent chapter index of co-occurrence.
  final int lastSeenChapter;

  /// Stable edge ID generated by sorting entity IDs alphabetically.
  static String generateId(String bookId, String id1, String id2, {String readThroughId = 'default'}) {
    final sorted = [id1, id2]..sort();
    return '$bookId:$readThroughId:${sorted[0]}:${sorted[1]}';
  }

  StoryCooccurrence copyWith({
    String? id,
    String? bookId,
    String? readThroughId,
    String? entityAId,
    String? entityBId,
    int? weight,
    int? lastSeenChapter,
  }) {
    return StoryCooccurrence(
      id: id ?? this.id,
      bookId: bookId ?? this.bookId,
      readThroughId: readThroughId ?? this.readThroughId,
      entityAId: entityAId ?? this.entityAId,
      entityBId: entityBId ?? this.entityBId,
      weight: weight ?? this.weight,
      lastSeenChapter: lastSeenChapter ?? this.lastSeenChapter,
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'bookId': bookId,
    'readThroughId': readThroughId,
    'entityAId': entityAId,
    'entityBId': entityBId,
    'weight': weight,
    'lastSeenChapter': lastSeenChapter,
  };
}

