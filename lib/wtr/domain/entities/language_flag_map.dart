/// Resolves an ISO-639-1 or BCP-47 language code to a 2-letter ISO-3166-1 country code.
String resolveCountryCodeForLanguage(String code) {
  final direct = kLanguageCountryCodes[code];
  if (direct != null) return direct;
  final base = code.split('-').first.toLowerCase();
  return kLanguageCountryCodes[base] ?? 'US';
}
